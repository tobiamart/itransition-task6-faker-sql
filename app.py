"""Fake user generator web app.

All data is generated by stored functions in the `faker` schema of PostgreSQL;
this app only calls them and renders the result.
"""
import os
import random
import secrets
import time
from pathlib import Path

import markdown
import psycopg
from flask import Flask, abort, g, jsonify, render_template, request
from psycopg.rows import dict_row

ROOT = Path(__file__).resolve().parent
app = Flask(__name__, template_folder=str(ROOT / 'templates'))

BATCH_SIZES = (10, 20, 50)
BENCHMARK_SIZES = (1000, 5000, 10000, 20000)
BENCHMARK_CACHE_SECONDS = 300   # repeated runs reuse the result instead of loading the database
STATEMENT_TIMEOUT = '30s'
SEED_MAX = 2 ** 53 - 1
_conn = None
_benchmark_cache = {}


def database_url():
    url = os.environ.get('DATABASE_URL')
    if url:
        return url
    import pgserver  # local development only (pip install pgserver)
    return pgserver.get_server(str(ROOT / '.pgdata'), cleanup_mode=None).get_uri()


def db():
    """One connection per warm worker; reconnect when it was closed."""
    global _conn
    if _conn is None or _conn.closed or _conn.broken:
        # prepare_threshold=None: no server-side prepared statements (safe behind a PgBouncer pooler)
        _conn = psycopg.connect(database_url(), autocommit=True, row_factory=dict_row, prepare_threshold=None)
    return _conn


def query(sql, params=()):
    def run():
        conn = db()
        with conn.transaction():   # SET LOCAL keeps the timeout inside this transaction (pooler safe)
            conn.execute(f"SET LOCAL statement_timeout = '{STATEMENT_TIMEOUT}'")
            return conn.execute(sql, params).fetchall()
    try:
        return run()
    except psycopg.OperationalError:
        global _conn
        _conn = None
        return run()


def locales():
    return query('SELECT code, name FROM faker.list_locales()')


def int_arg(name, default, lo, hi):
    try:
        value = int(request.args.get(name, default))
    except (TypeError, ValueError):
        abort(400, f'{name} must be an integer')
    if not lo <= value <= hi:
        abort(400, f'{name} must be between {lo} and {hi}')
    return value


def arguments():
    codes = {l['code'] for l in locales()}
    locale = request.args.get('locale', 'en_US')
    if locale not in codes:
        abort(400, f'unknown locale {locale}')
    seed = int_arg('seed', 42, 0, SEED_MAX)
    batch = int_arg('batch', 0, 0, 10 ** 7)
    size = int_arg('size', 10, 1, 1000)
    return locale, seed, batch, size


def generate(locale, seed, batch, size):
    t = time.perf_counter()
    rows = query('SELECT * FROM faker.generate_users(%s, %s, %s, %s)', (locale, seed, batch, size))
    return rows, (time.perf_counter() - t) * 1000


@app.get('/')
def index():
    locale, seed, batch, size = arguments()
    if size not in BATCH_SIZES:
        size = 10
    rows, ms = generate(locale, seed, batch, size)
    return render_template('index.html', rows=rows, ms=ms, locales=locales(), locale=locale, seed=seed,
                           batch=batch, size=size, sizes=BATCH_SIZES, random_seed=random.randint(0, 999999))


@app.get('/api/users')
def api_users():
    locale, seed, batch, size = arguments()
    rows, ms = generate(locale, seed, batch, size)
    for r in rows:
        r['height_cm'] = float(r['height_cm'])
        r['weight_kg'] = float(r['weight_kg'])
    return jsonify(locale=locale, seed=seed, batch=batch, size=size, milliseconds=round(ms, 1), users=rows)


@app.get('/benchmark')
def benchmark():
    results, cached_at = [], None
    n = int_arg('n', 10000, 1, 10 ** 6)
    if n not in BENCHMARK_SIZES:
        abort(400, f'n must be one of {", ".join(map(str, BENCHMARK_SIZES))}')
    if request.args.get('run'):
        hit = _benchmark_cache.get(n)
        if hit and time.time() - hit[0] < BENCHMARK_CACHE_SECONDS:
            cached_at, results = hit
        else:
            for code in [l['code'] for l in locales()]:
                t = time.perf_counter()
                r = query('SELECT * FROM faker.benchmark(%s, %s)', (code, n))[0]
                r['roundtrip'] = time.perf_counter() - t
                results.append(r)
            _benchmark_cache[n] = (time.time(), results)
    return render_template('benchmark.html', results=results, n=n, sizes=BENCHMARK_SIZES,
                           cached_age=None if cached_at is None else int(time.time() - cached_at))


@app.get('/docs')
def docs():
    text = (ROOT / 'docs' / 'FAKER_SQL.md').read_text(encoding='utf-8')
    html = markdown.markdown(text, extensions=['tables', 'fenced_code', 'toc'])
    return render_template('docs.html', content=html)


@app.before_request
def make_nonce():
    g.nonce = secrets.token_urlsafe(16)


@app.after_request
def security_headers(response):
    nonce = getattr(g, 'nonce', '')
    response.headers['Content-Security-Policy'] = (
        f"default-src 'self'; script-src 'nonce-{nonce}'; style-src 'self' 'unsafe-inline' https://cdn.jsdelivr.net; "
        "font-src https://cdn.jsdelivr.net; img-src 'self' data:; connect-src 'self'; object-src 'none'; "
        "base-uri 'self'; form-action 'self'; frame-ancestors 'none'")
    response.headers['X-Content-Type-Options'] = 'nosniff'
    response.headers['X-Frame-Options'] = 'DENY'
    response.headers['Referrer-Policy'] = 'strict-origin-when-cross-origin'
    response.headers['Permissions-Policy'] = 'camera=(), microphone=(), geolocation=()'
    return response


@app.errorhandler(400)
def bad_request(err):
    return render_template('error.html', message=err.description), 400


if __name__ == '__main__':
    os.environ.setdefault('DATABASE_URL', database_url())   # resolve the local server once, before threads start
    app.run(debug=True, port=5000, use_reloader=False)
